import streamlit as st
import pandas as pd
import plotly.express as px
import plotly.graph_objects as go
from datetime import datetime

from components.ui import html, page_header
from pages.common import load_logs, load_alerts, normalize_timestamp
from database import get_log_count, get_alert_count, get_high_alert_count, get_critical_alert_count

def threat_score(alert_count, high_count, critical_count, medium_count=0):
    # Transparent illustrative score based on stored alert severity.
    score = (critical_count * 25) + (high_count * 15) + (medium_count * 5)
    return min(int(score), 100)

def threat_level(score):
    if score >= 70:
        return "HIGH"
    if score >= 40:
        return "MEDIUM"
    return "LOW"

def show_dashboard():
    page_header("Security Overview", "Security monitoring and threat analysis")

    logs = load_logs()
    alerts = load_alerts()

    total_events = get_log_count()
    total_alerts = get_alert_count()
    high_count = get_high_alert_count()
    critical_count = get_critical_alert_count()
    medium_count = 0
    if not alerts.empty and "severity" in alerts.columns:
        medium_count = int((alerts["severity"].astype(str).str.upper() == "MEDIUM").sum())

    score = threat_score(total_alerts, high_count, critical_count, medium_count)
    level = threat_level(score)

    cards = st.columns(4, gap="medium")
    card_data = [
        ("TOTAL EVENTS", total_events, "📊", "Logs stored in MySQL"),
        ("SECURITY ALERTS", total_alerts, "🚨", "Generated by detection rules"),
        ("HIGH SEVERITY", high_count, "⚠️", "High-priority alerts"),
        ("CRITICAL THREATS", critical_count, "🔴", "Critical alerts"),
    ]
    for col, (title, value, icon, note) in zip(cards, card_data):
        with col:
            html(f"""
            <div class="kpi">
                <div class="kpi-top">
                    <div class="kpi-title">{title}</div>
                    <div class="kpi-icon">{icon}</div>
                </div>
                <div class="kpi-value">{value:,}</div>
                <div class="kpi-bottom"><span class="kpi-neutral">{note}</span></div>
            </div>
            """)

    st.write("")
    left, right = st.columns([2, 1], gap="medium")

    with left:
        html("""
        <div class="panel">
            <div class="panel-header">
                <div>
                    <div class="panel-title">Failed Login Activity</div>
                    <div class="panel-subtitle">Authentication failures in stored logs</div>
                </div>
            </div>
        </div>
        """)
        if not logs.empty and {"status", "timestamp"}.issubset(logs.columns):
            logs = normalize_timestamp(logs)
            failed = logs[logs["status"].astype(str).str.lower() == "failed"].copy()
            if not failed.empty:
                failed = failed.dropna(subset=["timestamp"])
                failed["Hour"] = failed["timestamp"].dt.strftime("%H:00")
                counts = failed.groupby("Hour").size().reset_index(name="Failed Logins").sort_values("Hour")
                fig = go.Figure(go.Scatter(
                    x=counts["Hour"], y=counts["Failed Logins"],
                    mode="lines+markers", fill="tozeroy",
                    line=dict(width=3),
                    hovertemplate="%{x}<br>Failed logins: %{y}<extra></extra>"
                ))
                fig.update_layout(
                    height=300, margin=dict(l=10, r=10, t=10, b=10),
                    paper_bgcolor="#0d1421", plot_bgcolor="#0d1421",
                    font=dict(color="#94a3b8"),
                    xaxis=dict(showgrid=False), yaxis=dict(gridcolor="#172236")
                )
                st.plotly_chart(fig, use_container_width=True, config={"displayModeBar": False})
            else:
                st.info("No failed login events found.")
        else:
            st.info("No log data available to chart.")

    with right:
        html(f"""
        <div class="panel">
            <div class="panel-header">
                <div>
                    <div class="panel-title">Threat Level</div>
                    <div class="panel-subtitle">Severity-weighted alert score</div>
                </div>
            </div>
            <div class="threat-score">
                <div class="score-circle">
                    <div class="score-number">{score}</div>
                    <div class="score-label">RISK SCORE</div>
                </div>
                <div class="threat-{level.lower()}">{level} THREAT</div>
                <div style="color:#64748b;font-size:10px;margin-top:8px;">
                    Based on current stored alerts
                </div>
            </div>
        </div>
        """)

    st.write("")
    left, right = st.columns(2, gap="medium")

    with left:
        html("""
        <div class="panel">
            <div class="panel-header">
                <div>
                    <div class="panel-title">Recent Security Alerts</div>
                    <div class="panel-subtitle">Latest generated alerts</div>
                </div>
            </div>
        </div>
        """)
        if not alerts.empty:
            for _, row in alerts.head(5).iterrows():
                severity = str(row.get("severity", "LOW")).upper()
                alert_type = row.get("alert_type", "Security Alert")
                ip = row.get("ip_address", "-")
                description = row.get("description", "")
                html(f"""
                <div class="alert-row">
                    <div class="severity sev-{severity.lower()}">{severity}</div>
                    <div class="alert-details">
                        <div class="alert-name">{alert_type}</div>
                        <div class="alert-meta">{ip} • {description}</div>
                    </div>
                </div>
                """)
        else:
            st.info("No security alerts generated yet.")

    with right:
        html("""
        <div class="panel">
            <div class="panel-header">
                <div>
                    <div class="panel-title">Attack Distribution</div>
                    <div class="panel-subtitle">Alerts grouped by detection type</div>
                </div>
            </div>
        </div>
        """)
        if not alerts.empty and "alert_type" in alerts.columns:
            distribution = alerts["alert_type"].fillna("Unknown").value_counts().reset_index()
            distribution.columns = ["Alert Type", "Count"]
            fig = px.pie(distribution, names="Alert Type", values="Count", hole=0.55)
            fig.update_layout(
                height=320, margin=dict(l=10, r=10, t=10, b=10),
                paper_bgcolor="#0d1421", font=dict(color="#94a3b8"),
                legend=dict(orientation="h", yanchor="bottom", y=-0.15)
            )
            st.plotly_chart(fig, use_container_width=True, config={"displayModeBar": False})
        else:
            st.info("No alerts available for distribution.")

    st.write("")
    left, right = st.columns(2, gap="medium")
    with left:
        html("""
        <div class="panel">
            <div class="panel-title">Top Alert Source IPs</div>
            <div class="panel-subtitle">Addresses appearing in stored alerts</div>
        </div>
        """)
        if not alerts.empty and "ip_address" in alerts.columns:
            ip_counts = alerts["ip_address"].dropna().astype(str).value_counts().head(5)
            if not ip_counts.empty:
                st.dataframe(ip_counts.rename_axis("IP Address").reset_index(name="Alert Count"), use_container_width=True, hide_index=True)
            else:
                st.info("No IP addresses recorded in alerts.")
        else:
            st.info("No suspicious IP data available.")
    with right:
        html(f"""
        <div class="panel">
            <div class="panel-title">Log Sources</div>
            <div class="panel-subtitle">Current database summary</div>
            <div class="source"><div class="source-name">Authentication Logs</div><div class="source-status">● AVAILABLE</div></div>
            <div class="source"><div class="source-name">CSV Import</div><div class="source-status">● AVAILABLE</div></div>
            <div class="source"><div class="source-name">MySQL Storage</div><div class="source-status">● CONNECTED</div></div>
        </div>
        """)
